#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

usage() {
  cat <<'EOF'
Run Presentalia with a local Supabase stack.

Usage:
  ./scripts/run-local.sh [Next.js dev options]
  npm run local -- [Next.js dev options]

Starts Supabase via Docker, writes local Supabase credentials to .env.local,
then starts Next.js. Docker Desktop/Engine must be installed and running.
EOF
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  usage
  exit 0
fi

NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
if [[ -s "$NVM_DIR/nvm.sh" ]]; then
  # shellcheck disable=SC1090
  source "$NVM_DIR/nvm.sh"
  if ! nvm use 24 >/dev/null; then
    echo "Node.js 24 is required. Install it with: nvm install 24" >&2
    exit 1
  fi
fi

if ! command -v node >/dev/null 2>&1; then
  echo "Node.js 24 and npm are required. Install Node.js 24, then rerun this script." >&2
  exit 1
fi

NODE_MAJOR="$(node -p 'Number(process.versions.node.split(".")[0])')"
if [[ "$NODE_MAJOR" -lt 24 ]]; then
  echo "Node.js 24 or newer is required (found $(node --version))." >&2
  exit 1
fi

if ! command -v npm >/dev/null 2>&1; then
  echo "npm was not found. Install Node.js 24 with npm, then rerun this script." >&2
  exit 1
fi

if [[ ! -d node_modules ]]; then
  npm ci
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker Desktop/Engine is required to run Supabase locally. Install Docker, then rerun this script." >&2
  exit 1
fi
if ! docker info >/dev/null 2>&1; then
  echo "Docker is installed but its daemon is not accessible. Start Docker Desktop/Engine and rerun this script." >&2
  exit 1
fi

if [[ ! -f supabase/config.toml ]]; then
  npx --no-install supabase init --workdir "$ROOT_DIR"
fi

npx --no-install supabase start
SUPABASE_ENV="$(npx --no-install supabase status -o env)"
eval "$SUPABASE_ENV"

if [[ -z "${API_URL:-}" || -z "${DB_URL:-}" || -z "${ANON_KEY:-}" || -z "${SERVICE_ROLE_KEY:-}" ]]; then
  echo "Could not read local Supabase credentials. Check 'npx supabase status -o env'." >&2
  exit 1
fi

existing_admin="${ADMIN_EMAIL:-}"
if [[ -z "$existing_admin" && -f .env.local ]]; then
  existing_admin="$(grep -E '^ADMIN_EMAIL=' .env.local | tail -n 1 | cut -d '=' -f 2- || true)"
  existing_admin="${existing_admin%\"}"
  existing_admin="${existing_admin#\"}"
  existing_admin="${existing_admin%\'}"
  existing_admin="${existing_admin#\'}"
fi
admin_email="${existing_admin:-admin@example.com}"

cat > .env.local <<EOF
# Generated by scripts/run-local.sh from the local Supabase stack.
NEXT_PUBLIC_SUPABASE_URL=$API_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
POSTGRES_URL=$DB_URL
SUPABASE_DB_URL=$DB_URL
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
ADMIN_EMAIL=$admin_email
NEXT_PUBLIC_SITE_URL=http://localhost:3000
EOF

echo "Local Supabase is running. Magic-link emails are available in the local email inbox at http://127.0.0.1:54324."
echo "Starting Presentalia at http://localhost:3000..."

exec npm run dev -- "$@"
